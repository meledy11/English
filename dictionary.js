// ПАРСИНГ RAW → объекты
// ═══════════════════════════════════════════════
const POS_EMOJI = {
    noun: '📦', verb: '⚡', adjective: '🎨', adverb: '💨',
    pronoun: '👤', preposition: '🧭', conjunction: '🔗',
    interjection: '😲', numeral: '🔢', particle: '✨',
    article: '📎', phrase: '💬'
};

const dictionary = RAW.map((line, i) => {
    const [eng, ru, tr, pos] = line.split('|');
    return {
        id: i + 1,
        eng: eng.trim(),
        ru: ru.trim(),
        tr: (tr || '').trim(),
        emoji: POS_EMOJI[(pos || 'noun').trim()] || '📖',
        pos: (pos || 'noun').trim(),
        ex1: '',
        tr1: ''
    };
});

// ═══════════════════════════════════════════════
// ОЗВУЧКА (Web Speech API)
// ═══════════════════════════════════════════════
function speakWord(text, lang = 'en-US', rate = 0.9) {
    if (!('speechSynthesis' in window)) {
        console.warn('Web Speech API не поддерживается');
        return;
    }
    window.speechSynthesis.cancel();
    const u = new SpeechSynthesisUtterance(text);
    u.lang = lang;
    u.rate = rate;
    window.speechSynthesis.speak(u);
}

// ═══════════════════════════════════════════════
// ПОИСК
// ═══════════════════════════════════════════════
function dictionaryLookup(query) {
    if (!query || !query.trim()) return [];
    const q = query.toLowerCase().trim();
    return dictionary.filter(item => 
        item.eng.toLowerCase().includes(q) || 
        item.ru.toLowerCase().includes(q)
    );
}

// Экспорт для использования в других скриптах
if (typeof window !== 'undefined') {
    window.dictionary = dictionary;
    window.speakWord = speakWord;
    window.dictionaryLookup = dictionaryLookup;
    console.log(`✅ Словарь загружен: ${dictionary.length} слов`);
}
